import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const REVISION = '525f9b560de45753a5ea01069454e72e9aa541c6';
const SOURCE_URL = `https://raw.githubusercontent.com/hermitdave/FrequencyWords/${REVISION}/content/2018/en/en_50k.txt`;
const SOURCE_SHA256 = '5351ff405b1126ef555791dd4d9798a48e3e9a501a9fc481a9da957752cfb458';
const OUTPUT = fileURLToPath(new URL('../extension/frequency/english-frequency.js', import.meta.url));

const response = await fetch(SOURCE_URL);
if (!response.ok) throw new Error(`Frequency source returned HTTP ${response.status}`);
const source = await response.text();
const digest = createHash('sha256').update(source).digest('hex');
if (digest !== SOURCE_SHA256) throw new Error(`Frequency source checksum mismatch: ${digest}`);

const words = [];
const seen = new Set();
for (const row of source.split('\n')) {
  const match = /^([^ ]+) (\d+)\r?$/.exec(row);
  if (!match) continue;
  const word = match[1].toLowerCase();
  // Keep English lexical tokens only. The source also contains punctuation,
  // markup fragments, numbers and tokens from subtitle metadata.
  if (!/^[a-z]+(?:['-][a-z]+)*$/.test(word) || seen.has(word)) continue;
  seen.add(word);
  words.push(word);
}

const header = `// Generated by tools/build-frequency-data.mjs; do not edit.\n`
  + `// Frequency rank is an OpenSubtitles usage proxy, not a CEFR classification.\n`
  + `export const FREQUENCY_SOURCE = Object.freeze({\n`
  + `  repository: 'hermitdave/FrequencyWords',\n`
  + `  revision: '${REVISION}',\n`
  + `  file: 'content/2018/en/en_50k.txt',\n`
  + `  sha256: '${SOURCE_SHA256}',\n`
  + `  license: 'CC-BY-SA-4.0',\n`
  + `});\n`
  + `const RANKED_WORDS = `;
const body = `${JSON.stringify(words.join('\n'))}.split('\\n');\n`
  + `export const ENGLISH_FREQUENCY_RANK = new Map(RANKED_WORDS.map((word, index) => [word, index + 1]));\n`
  + `export const ENGLISH_FREQUENCY_WORD_COUNT = RANKED_WORDS.length;\n`;
await writeFile(OUTPUT, header + body, 'utf8');
console.log(`Wrote ${words.length} ranked words to ${OUTPUT}`);
